/**
 * Indices in the equity section: every NSE and BSE index Kite lists, backtested and screened on their own daily
 * candles — as TradingView's strategy tester does on an index chart. Keys: an NSE index by Kite's symbol
 * ("NIFTY 50", "NIFTY BANK"); a BSE index "BSE:<Kite symbol>" ("BSE:SENSEX"). Never a stock symbol: NSE stock symbols
 * have no spaces or ":" (checked against Kite's lists, 2026-10-21).
 * `tv` = TradingView's symbol (null where TradingView has no chart). Kite adds indices over time — one missing here
 * still loads (group OTHER / BSE, Kite's name, no chart link). Not listed: HANGSENG BEES-NAV (an ETF's NAV, no candles).
 */

export type EqIndexGroup = 'BROAD' | 'SECTOR' | 'THEME' | 'STRATEGY' | 'OTHER' | 'BSE';

