/** The key of a BSE index: "BSE:" + Kite's symbol (an NSE index is Kite's symbol itself). */
export const bseIndexKey = (kiteSymbol: string) => `BSE:${kiteSymbol}`;

/** Other names the stock search finds an index by: its F&O name and its TradingView symbol (BANKNIFTY, CNXIT). */
export function indexAliases(symbol: string): string[] {
  const ix = EQ_INDICES[symbol];
  if (!ix) return [];
  return [ix.fno, ix.tv?.slice(ix.tv.indexOf(':') + 1)].filter((a): a is string => !!a);
}

/** An index rather than a stock (stocks have no spaces or ":"). */
export const isIndexSymbol = (symbol: string) => symbol in EQ_INDICES || symbol.includes(' ') || symbol.includes(':');

/** TradingView's symbol for a stock or index — null when TradingView has no chart for it. TradingView writes NSE's
 *  "-" as "_" (BAJAJ-AUTO → NSE:BAJAJ_AUTO) and keeps "&" (NSE:M&M). */
export function tradingViewSymbol(symbol: string): string | null {
  const ix = EQ_INDICES[symbol];
  if (ix) return ix.tv;
  return isIndexSymbol(symbol) ? null : `NSE:${symbol.replace(/-/g, '_')}`;
}
